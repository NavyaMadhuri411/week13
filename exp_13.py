# Experiment 13: RAG Chain Using LCEL, FAISS, and Gemini

# %pip install -q -U langchain-core langchain-community langchain-text-splitters langchain-google-genai faiss-cpu

import os
from getpass import getpass

from langchain_core.documents import Document
from langchain_core.prompts import ChatPromptTemplate
from langchain_core.output_parsers import StrOutputParser
from langchain_core.runnables import RunnablePassthrough
from langchain_text_splitters import RecursiveCharacterTextSplitter
from langchain_google_genai import (
    ChatGoogleGenerativeAI,
    GoogleGenerativeAIEmbeddings
)
from langchain_community.vectorstores import FAISS

# --------------------------------------------------
# STEP 1: Configure Gemini API key
# --------------------------------------------------

os.environ.pop("GOOGLE_API_KEY", None)
os.environ["GOOGLE_API_KEY"] = getpass(
    "Enter your Gemini API key: "
)

# --------------------------------------------------
# STEP 2: Define the climate-change document
# Reusing the text from Experiment 12
# --------------------------------------------------

sample_text = """
Climate change refers to long-term changes in temperatures
and weather patterns. Human activities, especially burning
fossil fuels such as coal, oil, and gas, are the main drivers
of recent global warming.

One major effect of climate change is rising global temperature.
Heat waves are becoming more frequent and intense in many regions.
Higher temperatures can affect human health, agriculture,
water supplies, and natural ecosystems.

Climate change also contributes to melting glaciers and polar ice.
As land ice melts and ocean water expands when heated,
sea levels rise. Coastal communities may experience more flooding,
erosion, and damage to buildings and infrastructure.

Extreme weather events such as heavy rainfall, droughts, and
some severe storms can create serious challenges. These events
may damage crops, disrupt transportation, and threaten wildlife.
The exact effects vary by location and depend on local conditions.

Reducing greenhouse gas emissions can help limit future warming.
Renewable energy sources such as solar and wind power can reduce
dependence on fossil fuels. Energy efficiency, forest protection,
and sustainable transportation can also help address climate change.
"""

# --------------------------------------------------
# STEP 3: Split the text into chunks
# --------------------------------------------------

document = Document(
    page_content=sample_text,
    metadata={"source": "climate_change_text"}
)

splitter = RecursiveCharacterTextSplitter(
    chunk_size=300,
    chunk_overlap=30
)

chunks = splitter.split_documents([document])
print("Number of chunks:", len(chunks))

# --------------------------------------------------
# STEP 4: Generate embeddings and build FAISS index
# --------------------------------------------------

embeddings = GoogleGenerativeAIEmbeddings(
    model="models/gemini-embedding-001"
)

vectorstore = FAISS.from_documents(
    documents=chunks,
    embedding=embeddings
)

print("FAISS index created successfully.")

# --------------------------------------------------
# STEP 5: Create a retriever for the top 2 chunks
# --------------------------------------------------

retriever = vectorstore.as_retriever(
    search_kwargs={"k": 2}
)

# --------------------------------------------------
# STEP 6: Define the RAG prompt
# --------------------------------------------------

prompt = ChatPromptTemplate.from_template("""
You are a question-answering assistant.

Answer the question using ONLY the context provided below.
Do not add facts that are not supported by the context.
If the context does not contain the answer, say:
"I don't know based on the provided text."

Context:
{context}

Question:
{question}

Answer:
""")

# --------------------------------------------------
# STEP 7: Configure Gemini chat model and parser
# --------------------------------------------------

llm = ChatGoogleGenerativeAI(
    model="gemini-3.8-flash",
    temperature=0
)

parser = StrOutputParser()

# Convert retrieved Document objects into one text string
def format_docs(docs):
    return "\n\n".join(
        doc.page_content for doc in docs
    )

# --------------------------------------------------
# STEP 8: Build the LCEL RAG chain
# --------------------------------------------------

rag_chain = (
    {
        "context": retriever | __import__(
            "langchain_core.runnables",
            fromlist=["RunnableLambda"]
        ).RunnableLambda(format_docs),
        "question": RunnablePassthrough()
    }
    | prompt
    | llm
    | parser
)

# --------------------------------------------------
# STEP 9: Test the chain on two questions
# --------------------------------------------------

questions = [
    "What are the effects of climate change?",
    "What causes climate change, and how can it be reduced?"
]

all_results = []

for question in questions:
    print("\n" + "=" * 60)
    print("Question:", question)

    try:
        # Retrieve chunks for transparent verification
        retrieved_docs = retriever.invoke(question)

        # Generate the grounded answer
        answer = rag_chain.invoke(question)

        print("\nAnswer:")
        print(answer)

        print("\nRetrieved Chunks:")
        for index, doc in enumerate(retrieved_docs, start=1):
            print(f"\nChunk {index}:")
            print(doc.page_content)

        all_results.append({
            "question": question,
            "answer": answer,
            "chunks": [
                doc.page_content for doc in retrieved_docs
            ]
        })

    except Exception as error:
        print("Error:", error)
        print(
            "Check your Gemini API key, model availability, "
            "internet connection, and API quota."
        )

# --------------------------------------------------
# STEP 10: Save results
# --------------------------------------------------

with open("output.txt", "w", encoding="utf-8") as file:
    for result in all_results:
        file.write(f"Question: {result['question']}\n")
        file.write(f"Answer: {result['answer']}\n")
        file.write("Retrieved Chunks:\n")

        for index, chunk in enumerate(result["chunks"], start=1):
            file.write(f"\nChunk {index}:\n{chunk}\n")

        file.write("\n" + "-" * 60 + "\n\n")

print("\nSuccessful results saved to output.txt")

